using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;
using EfQuery = Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions;
using LinqQuery = System.Linq.Queryable;

namespace InventoryContractFixtures;

public sealed class Widget
{
    public int Id { get; set; }
    public bool Active { get; set; }
    public string Json { get; set; } = "{}";
}

public sealed class FixtureContext : DbContext
{
    public DbSet<Widget> Widgets => Set<Widget>();
}

public sealed class FakeSequence<T>;

public static class SameNamedExtensions
{
    public static Task<List<T>> ToListAsync<T>(this FakeSequence<T> source,
        CancellationToken token = default) => Task.FromResult(new List<T>());
}

public abstract class BaseRepository<TEntity> where TEntity : class
{
    protected abstract DbSet<TEntity> GetDbSet(FixtureContext context);
    protected virtual IQueryable<TEntity> ApplyDefaultIncludes(IQueryable<TEntity> query) => query;

    public Task<List<TEntity>> BaseGenericTerminal(FixtureContext context, CancellationToken token) =>
        ApplyDefaultIncludes(GetDbSet(context)).ToListAsync(token);
}

public static class SemanticCases
{
    public const string MarkerInUserData = "<auto-generated/>";

    public static Task<List<Widget>> InlineEfRoot(FixtureContext context, CancellationToken token) =>
        context.Set<Widget>().AsNoTracking().Where(widget => widget.Active).ToListAsync(token);

    public static Task<List<Widget>> AliasStaticEfRoot(FixtureContext context, CancellationToken token) =>
        EfQuery.ToListAsync(context.Widgets.Where(widget => widget.Active), token);

    public static Task<List<Widget>> ReorderedNamedArgumentRoot(FixtureContext context, CancellationToken token) =>
        EfQuery.ToListAsync(cancellationToken: token, source: context.Widgets);

    public static int QueryableTerminal(FixtureContext context) =>
        LinqQuery.Count(context.Widgets.Where(widget => widget.Active));

    public static int UnknownQueryableParameter(IQueryable<Widget> query) => query.Count();

    public static Task<List<Widget>> CustomSameNamedTerminal(FakeSequence<Widget> source,
        CancellationToken token) => source.ToListAsync(token);

    public static int EnumerableTerminal(FixtureContext context) =>
        context.Widgets.AsEnumerable().Count();

    public static List<Widget> EnumerableMaterializer(IEnumerable<Widget> source) => source.ToList();

    public static Task<List<Widget>> MutableAliasTerminal(FixtureContext context, bool filter,
        CancellationToken token)
    {
        IQueryable<Widget> query = context.Widgets;
        if (filter)
        {
            query = query.Where(widget => widget.Active);
        }
        return query.ToListAsync(token);
    }

    public static Task<List<Widget>> QuerySyntaxTerminal(FixtureContext context, CancellationToken token)
    {
        var query = from widget in context.Widgets
                    where widget.Active
                    select widget;
        return query.ToListAsync(token);
    }

    private static IQueryable<Widget> CreateQuery(FixtureContext context) => context.Widgets;

    public static Task<List<Widget>> OpaqueHelperTerminal(FixtureContext context, CancellationToken token) =>
        CreateQuery(context).ToListAsync(token);

    public static Task<List<Widget>> ExpressionArgumentTerminal(FixtureContext context,
        Expression<Func<Widget, bool>> predicate, CancellationToken token) =>
        context.Widgets.Where(predicate).ToListAsync(token);

    public static Task<List<Widget>> NpgsqlPredicateTerminal(FixtureContext context, CancellationToken token) =>
        context.Widgets.Where(widget => EF.Functions.JsonContains(widget.Json, "{}"))
            .ToListAsync(token);

    public static Task<int> RawSqlCommand(FixtureContext context, CancellationToken token) =>
        context.Database.ExecuteSqlRawAsync("DELETE FROM fixture_contract", token);

    public static Task<List<Widget>> RawSqlQuery(FixtureContext context, CancellationToken token) =>
        context.Widgets.FromSqlRaw("SELECT * FROM fixture_contract").ToListAsync(token);

    public static Task<int> BulkMutation(FixtureContext context, CancellationToken token) =>
        context.Widgets.Where(widget => !widget.Active).ExecuteDeleteAsync(token);

    public static Task<int> SaveMutation(FixtureContext context, CancellationToken token) =>
        context.SaveChangesAsync(token);

    public static Task<int> NpgsqlAdoCommand(Npgsql.NpgsqlCommand command, CancellationToken token) =>
        command.ExecuteNonQueryAsync(token);

#if CONDUIT_NATIVE_AOT
    public static Task<List<Widget>> NativeProfileOnly(FixtureContext context, CancellationToken token) =>
        context.Widgets.ToListAsync(token);
#else
    public static Task<List<Widget>> JitProfileOnly(FixtureContext context, CancellationToken token) =>
        context.Widgets.ToListAsync(token);
#endif
}
